#!/bin/zsh

# Interactively set up ff-code configuration file

#USAGE ff-setup.sh

ENV_FILE="$HOME/.config/ff-code/env"

# Trap for Ctrl+C - exit without saving
trap 'echo -e "\nSetup cancelled."; exit 1' INT TERM

# Source existing config if present (pre-populates current values)
if [[ -f "$ENV_FILE" ]]; then
  source "$ENV_FILE"
fi

# Set defaults if not set
FACE_DIR="${FACE_DIR:-$HOME/Faces}"
TARGET_DIR="${TARGET_DIR:-$HOME/Videos}"
OUTPUT_DIR="${OUTPUT_DIR:-$HOME/tmp/facefusion}"
FF_DIR="${FF_DIR:-$HOME/.facefusion/facefusion}"
CONDA_ENV="${CONDA_ENV:-facefusion}"

echo "=== FaceFusion Setup ==="
echo "Press [Enter] to keep current value, type new value, or 's' to skip"
echo ""

# Array of variables to configure
declare -A VARS=(
  [FACE_DIR]="$FACE_DIR"
  [TARGET_DIR]="$TARGET_DIR"
  [OUTPUT_DIR]="$OUTPUT_DIR"
  [FF_DIR]="$FF_DIR"
  [CONDA_ENV]="$CONDA_ENV"
)

declare -A DESC_MAP=(
  [FACE_DIR]="Face source directory"
  [TARGET_DIR]="Target directory"
  [OUTPUT_DIR]="Output directory"
  [FF_DIR]="FaceFusion installation directory"
  [CONDA_ENV]="Conda environment name"
)

for VAR_NAME in "${(k)VARS[@]}"; do
  CURRENT="$VARS[$VAR_NAME]"
  DESC="$DESC_MAP[$VAR_NAME]"

  echo "$DESC ($VAR_NAME)"
  echo "  Current: $CURRENT"
  echo -n "  New value ([Enter]=keep, 's'=skip): "
  read -r input

  if [[ "$input" == "s" || "$input" == "S" ]]; then
    echo "  Skipped"
  elif [[ -n "$input" ]]; then
    VARS[$VAR_NAME]="$input"
    echo "  Set to: $input"
  else
    echo "  Kept: $CURRENT"
  fi
  echo ""
done

CONFIG_CONTENT=$(cat <<EOF
# FaceFusion Configuration
# Generated by ff-setup.sh

# Face source directory
FACE_DIR=${VARS[FACE_DIR]}

# Target directory (default input location)
TARGET_DIR=${VARS[TARGET_DIR]}

# Output directory for processed files
OUTPUT_DIR=${VARS[OUTPUT_DIR]}

# FaceFusion installation directory
FF_DIR=${VARS[FF_DIR]}

# Conda environment name (or full path)
CONDA_ENV=${VARS[CONDA_ENV]}
EOF
)

printf '%s' "$CONFIG_CONTENT" > "$ENV_FILE"

if [[ $? -ne 0 ]]; then
  echo "Error: Failed to write $ENV_FILE"
  exit 1
fi

echo "Setup complete! Configuration saved to $ENV_FILE"